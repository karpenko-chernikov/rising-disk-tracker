"""Подробный текстовый отчёт для человека."""

from __future__ import annotations

from typing import Any


def _f(x, fmt=".4g"):
    if x is None:
        return "н/д"
    try:
        if isinstance(x, float) and (x != x):  # nan
            return "н/д"
        return format(x, fmt)
    except Exception:
        return str(x)


def построить_отчёт(
    *,
    имя_файла: str,
    день: str,
    info: dict[str, Any],
    params_n,
    params_d,
    W_мм_с,
    раскладка: dict,
    r_кол: float,
    сводка: dict[str, Any],
    модель_сравнение: dict[str, Any] | None = None,
) -> str:
    lines: list[str] = []
    a = lines.append

    a("=" * 60)
    a("ОТЧЁТ ТРЕКЕРА «ПОДНИМАЮЩИЙСЯ ДИСК»")
    a("=" * 60)
    a("")
    a("Этот файл объясняет ВСЕ основные числа. Их же смотрите в мета.json, Excel и на графиках.")
    a("")

    a("── 1. ИСХОДНИК И ПАРАМЕТРЫ ОПЫТА ──")
    a(f"Файл видео: {имя_файла}")
    a(f"Дата съёмки (папка прогона): {день}")
    a(f"Частота кадров fps: {info.get('fps')} — сколько кадров в секунду записал телефон/камера.")
    a(f"Число кадров: {info.get('n_frames')} — длина ролика в кадрах.")
    a(f"Разрешение: {info.get('width')}×{info.get('height')} пикселей.")
    a("")
    a("Из ИМЕНИ файла (не из картинки):")
    a(f"  n = {_f(params_n)} об/мин — угловая скорость ВЕДУЩЕГО КОЛЕСА (привода).")
    a(f"  δ = {_f(params_d)} мм — смещение точки контакта ведущего ролика относительно геометрического центра диска.")
    a("       Знак: d+N / dN → контакт ВЫШЕ центра на N мм; d-N → контакт НИЖЕ центра на N мм; d0 → на высоте центра.")
    a("       (Верх = к потолку, как на камере. Горизонтальный сдвиг в δ не входит.)")
    a(f"Радиус ведущего колеса r_кол = {r_кол} мм (из настройки/установка.yaml).")
    if W_мм_с is not None:
        a(f"  W = {_f(W_мм_с, '.2f')} мм/с — ЛИНЕЙНАЯ скорость привода: W = 2π·n/60 · r_кол.")
        a("  Именно W входит в уравнения модели Maas (не об/мин диска).")
    else:
        a("  W = н/д — в имени не было n, либо не задан r_кол.")
    a("")
    a("С диска (из раскладки меток / yaml, спросили при «метки»):")
    a(f"  ID диска: {раскладка.get('id_диска')}")
    a(f"  R = {раскладка.get('R_мм')} мм — радиус диска.")
    a(f"  m = {раскладка.get('масса_г')} г — масса диска (для оценки энергий).")
    a(f"  сторона ArUco a = {раскладка.get('сторона_aruco_мм')} мм — эталон масштаба мм/пиксель.")
    a("")

    a("── 2. КАЧЕСТВО ТРЕКИНГА ──")
    м = сводка.get("метки") or {}
    a(м.get("описание") or "")
    a(
        f"Доля кадров, где центр диска вообще посчитан: "
        f"{100 * (сводка.get('доля_кадров_с_треком') or 0):.1f}%."
    )
    a("Если доля <30% — плохой свет/фокус/метки/ракурс; цифры по динамике ненадёжны.")
    cal = сводка.get("калибровка") or {}
    if cal.get("описание"):
        a(cal["описание"])
    if cal.get("предупреждение"):
        a("⚠ " + cal["предупреждение"])
    a("")

    a("── 3. ДИНАМИКА ДИСКА (что измерил CV) ──")
    a("Y, Z — координаты ЦЕНТРА диска в метрах (нуль ≈ первые 2 с ролика).")
    a("  +Y вправо по кадру, +Z вверх по кадру.")
    a(f"  σ(Y) = {_f(сводка.get('Y_sigma'))} м — разброс смещения вбок (больше → сильнее «шатание» по Y).")
    a(f"  σ(Z) = {_f(сводка.get('Z_sigma'))} м — разброс по «подъёму».")
    a(f"  max |r_ЦМ| = {_f(сводка.get('r_cm_макс'))} м — максимальное удаление центра от нуля.")
    a("")
    a("Ω (Omega) — угловая скорость САМОГО ДИСКА, рад/с (производная угла β).")
    a(f"  ⟨Ω⟩ = {_f(сводка.get('Omega_среднее'))} рад/с — среднее за ролик.")
    a(f"  σ(Ω) = {_f(сводка.get('Omega_sigma'))} рад/с — разброс; малый при устойчивом вращении.")
    a(f"  |Ω|_max = {_f(сводка.get('Omega_макс'))} рад/с — пик по модулю.")
    a("")
    a(сводка.get("режим_описание") or f"Режим: {сводка.get('режим')}")
    a("")

    a("── 4. СПЕКТР И ПЕРИОД ──")
    sp = сводка.get("спектр") or {}
    a(sp.get("описание") or "")
    per = сводка.get("период") or {}
    a(per.get("описание") or "")
    a("")

    a("── 5. ХАОС / ПРЕДСКАЗУЕМОСТЬ ──")
    ly = сводка.get("ляпунов") or {}
    a(ly.get("описание") or "")
    a(
        f"Число точек сечения Пуанкарé (Y=0 снизу вверх): {сводка.get('n_точек_пуанкаре')}. "
        "Много упорядоченных точек → периодика; облако → хаос. См. график пуанкаре_*.png."
    )
    a("")

    a("── 6. ЭНЕРГИИ (оценки) ──")
    a("Ek вращ. ≈ ½ I Ω², I≈½ m R² — вращательная кинетическая.")
    a("Ek поступ. ≈ ½ m (vY²+vZ²) — поступательная.")
    a("E грав. ≈ m g Z — прокси «поднятия» (нуль относительный!).")
    a("Это оценки порядка величины, не полный энергобаланс с трением.")
    a("")

    if модель_сравнение:
        a("── 7. СРАВНЕНИЕ С МОДЕЛЬЮ Maas ──")
        a(модель_сравнение.get("описание") or "")
        a("")

    a("── 8. ГДЕ СМОТРЕТЬ ФАЙЛЫ ──")
    a("ряд_по_времени.xlsx — каждый кадр; лист «словарь» объясняет колонки.")
    a("графики/ — PNG с подписями осей и смыслом.")
    a("наложения/трек_хвост.mp4 — видео + ускользающий хвост центра.")
    a("наложения/трек_полный.mp4 — видео + вся траектория центра.")
    a("  На оверлее: жёлтые рамки = ArUco; точка = центр диска; розовая стрелка = угол β;")
    a("  голубая линия = путь центра; числа слева = см. легенду на видео / этот отчёт.")
    a("мета.json — те же числа в машиночитаемом виде.")
    a("")
    a("Конец отчёта.")
    return "\n".join(lines) + "\n"
